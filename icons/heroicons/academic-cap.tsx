'use client';

import type {
  LegacyAnimationControls,
  ResolvedValues,
  VisualElement,
} from 'motion';
import type { Variants } from 'motion/react';
import type { ForwardedRef, HTMLAttributes } from 'react';
import {
  forwardRef,
  useCallback,
  useEffect,
  useImperativeHandle,
  useMemo,
  useRef,
  useState,
} from 'react';
import { getDefaultValueType, setTarget, visualElementStore } from 'motion';
import { motion, useAnimation } from 'motion/react';

import { cn } from '@/lib/utils';

export interface HeroiconsAcademicCapIconHandle {
  startAnimation: () => void;
  stopAnimation: () => void;
}
interface HeroiconsAcademicCapIconProps extends HTMLAttributes<HTMLDivElement> {
  size?: number;
}
const CAP_VARIANTS: Variants = {
  normal: {
    rotate: 0,
  },
  animate: {
    y: [0, -2, 0],
    rotate: [0, -2, 2, 0],
    transition: {
      duration: 0.6,
      ease: 'easeInOut',
    },
  },
};
const TASSEL_VARIANTS: Variants = {
  normal: { rotate: 0 },
  animate: {
    rotate: [0, 15, -10, 5, 0],
    transition: {
      duration: 0.8,
      ease: 'easeInOut',
      delay: 0.1,
    },
  },
};
const HeroiconsAcademicCapIcon = forwardRef<
  HeroiconsAcademicCapIconHandle,
  HeroiconsAcademicCapIconProps
>(({ onMouseEnter, onMouseLeave, className, size = 28, ...props }, ref) => {
  const controls = useAnimation();
  const isControlledRef = useRef(false);
  const {
    rootRef: iconRootRef,
    reduceDefinition,
    ...iconAccessibility
  } = useIconAccessibility(ref, () => {
    isControlledRef.current = ref != null;
    return {
      startAnimation: () => controls.start('animate'),
      stopAnimation: () => controls.start('normal'),
    };
  }, [controls]);
  const handleMouseEnter = useCallback(
    (e: React.MouseEvent<HTMLDivElement>) => {
      if (isControlledRef.current) {
        void e;
      } else {
        controls.start('animate');
      }
    },
    [controls]
  );
  const handleMouseLeave = useCallback(
    (e: React.MouseEvent<HTMLDivElement>) => {
      if (isControlledRef.current) {
        void e;
      } else {
        controls.start('normal');
      }
    },
    [controls]
  );
  return (
    <div
      className={cn(className)}
      {...props}
      ref={iconRootRef}
      onMouseEnter={(event) => {
        if (!iconAccessibility.controlled && !iconAccessibility.reduced) {
          handleMouseEnter(event);
        }
        onMouseEnter?.(event);
      }}
      onMouseLeave={(event) => {
        if (!iconAccessibility.controlled) {
          handleMouseLeave(event);
        }
        onMouseLeave?.(event);
      }}
      onFocus={(event) => {
        if (!iconAccessibility.controlled && !iconAccessibility.reduced) {
          iconAccessibility.startAnimation();
        }
        props.onFocus?.(event);
      }}
      onBlur={(event) => {
        if (!iconAccessibility.controlled) {
          iconAccessibility.stopAnimation();
        }
        props.onBlur?.(event);
      }}
    >
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="1.5"
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
      >
        <motion.g
          animate={reduceDefinition(controls)}
          style={{ transformOrigin: '12px 12px' }}
          variants={CAP_VARIANTS}
        >
          <path d="M4.259 10.147A50.636 50.636 0 0 0 1.601 9.334 59.906 59.906 0 0 1 12 3.493 59.903 59.903 0 0 1 22.399 9.333C21.503 9.581 20.616 9.853 19.741 10.147" />
          <path d="M4.259 10.147A50.717 50.717 0 0 1 12 13.489 50.702 50.702 0 0 1 19.74 10.147" />
          <path d="M4.26 10.147A60.438 60.438 0 0 0 3.769 16.494 48.62 48.62 0 0 1 12 20.904 48.62 48.62 0 0 1 20.232 16.494 60.46 60.46 0 0 0 19.741 10.147" />
          <path d="M6.75 15A0.75 0.75 0 1 0 6.75 13.5 0.75 0.75 0 0 0 6.75 15Z" />
          <path d="M4.993 19.993A5.981 5.981 0 0 0 6.75 15.75V14.25" />

          <motion.path
            d="M6.75 15V11.325A55.378 55.378 0 0 1 12 8.443"
            style={{
              transformBox: 'fill-box',
              transformOrigin: 'top center',
            }}
            variants={TASSEL_VARIANTS}
          />
        </motion.g>
      </svg>
    </div>
  );
});
