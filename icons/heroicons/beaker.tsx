'use client';

import type {
  LegacyAnimationControls,
  ResolvedValues,
  VisualElement,
} from 'motion';
import type { ForwardedRef, HTMLAttributes } from 'react';
import {
  forwardRef,
  useCallback,
  useEffect,
  useImperativeHandle,
  useMemo,
  useRef,
  useState,
} from 'react';
import { getDefaultValueType, setTarget, visualElementStore } from 'motion';
import { motion, useAnimation } from 'motion/react';

import { cn } from '@/lib/utils';

export interface HeroiconsBeakerIconHandle {
  startAnimation: () => void;
  stopAnimation: () => void;
}
interface HeroiconsBeakerIconProps extends HTMLAttributes<HTMLDivElement> {
  size?: number;
}
const HeroiconsBeakerIcon = forwardRef<
  HeroiconsBeakerIconHandle,
  HeroiconsBeakerIconProps
>(({ onMouseEnter, onMouseLeave, className, size = 28, ...props }, ref) => {
  const controls = useAnimation();
  const isControlledRef = useRef(false);
  const {
    rootRef: iconRootRef,
    reduceDefinition,
    ...iconAccessibility
  } = useIconAccessibility(ref, () => {
    isControlledRef.current = ref != null;
    return {
      startAnimation: () => controls.start('animate'),
      stopAnimation: () => controls.start('normal'),
    };
  }, [controls]);
  const handleMouseEnter = useCallback(
    (e: React.MouseEvent<HTMLDivElement>) => {
      if (isControlledRef.current) {
        void e;
      } else {
        controls.start('animate');
      }
    },
    [controls]
  );
  const handleMouseLeave = useCallback(
    (e: React.MouseEvent<HTMLDivElement>) => {
      if (isControlledRef.current) {
        void e;
      } else {
        controls.start('normal');
      }
    },
    [controls]
  );
  return (
    <div
      className={cn(className)}
      {...props}
      ref={iconRootRef}
      onMouseEnter={(event) => {
        if (!iconAccessibility.controlled && !iconAccessibility.reduced) {
          handleMouseEnter(event);
        }
        onMouseEnter?.(event);
      }}
      onMouseLeave={(event) => {
        if (!iconAccessibility.controlled) {
          handleMouseLeave(event);
        }
        onMouseLeave?.(event);
      }}
      onFocus={(event) => {
        if (!iconAccessibility.controlled && !iconAccessibility.reduced) {
          iconAccessibility.startAnimation();
        }
        props.onFocus?.(event);
      }}
      onBlur={(event) => {
        if (!iconAccessibility.controlled) {
          iconAccessibility.stopAnimation();
        }
        props.onBlur?.(event);
      }}
    >
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="1.5"
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
      >
        <motion.g
          animate={reduceDefinition(controls)}
          variants={{
            normal: { rotate: 0, translateY: 0 },
            animate: {
              translateY: -12,
              rotate: [0, 5, -5, 3, -3, 0],
              transition: {
                ease: 'linear',
                rotate: { duration: 0.8 },
              },
            },
          }}
        ></motion.g>
        <motion.g
          animate={reduceDefinition(controls)}
          variants={{
            normal: { rotate: 0, scale: 1 },
            animate: {
              scale: 0.9,
              rotate: [0, 6, -6, 3, -3, 0],
              transition: {
                duration: 0.8,
                scale: {
                  duration: 0.3,
                  type: 'spring',
                  bounce: 0.4,
                  stiffness: 150,
                  damping: 10,
                },
              },
            },
          }}
        >
          <path d="M9.75 3.104C9.499 3.127 9.249 3.154 9 3.186" />
          <path d="M9.75 3.104A24.301 24.301 0 0 1 14.25 3.104" />
          <path d="M14.25 3.104C14.501 3.127 14.751 3.154 15 3.186" />

          <path d="M9.75 3.104V8.818A2.25 2.25 0 0 1 9.091 10.409L5 14.5" />
          <path d="M14.25 3.104V8.818C14.25 9.415 14.487 9.988 14.909 10.409L19.8 15.3" />
          <path d="M19.8 15.3L18.23 15.693A9.065 9.065 0 0 1 12 15 9.065 9.065 0 0 0 5.77 14.307L5 14.5" />
          <path d="M19.8 15.3L21.202 16.702C22.434 17.934 21.852 20.02 20.135 20.313A48.309 48.309 0 0 1 12 21C9.227 21 6.509 20.765 3.865 20.313 2.147 20.02 1.565 17.934 2.798 16.703L5 14.5" />
        </motion.g>
      </svg>
    </div>
  );
});
