'use client';

import type {
  LegacyAnimationControls,
  ResolvedValues,
  VisualElement,
} from 'motion';
import type { ForwardedRef, HTMLAttributes } from 'react';
import {
  forwardRef,
  useCallback,
  useEffect,
  useImperativeHandle,
  useMemo,
  useRef,
  useState,
} from 'react';
import { getDefaultValueType, setTarget, visualElementStore } from 'motion';
import { motion, useAnimation } from 'motion/react';

import { cn } from '@/lib/utils';

export interface HugeiconsHandFistIconHandle {
  startAnimation: () => void;
  stopAnimation: () => void;
}
interface HugeiconsHandFistIconProps extends HTMLAttributes<HTMLDivElement> {
  size?: number;
}
const HugeiconsHandFistIcon = forwardRef<
  HugeiconsHandFistIconHandle,
  HugeiconsHandFistIconProps
>(
  (
    {
      onMouseEnter,
      onMouseLeave,
      onFocus,
      onBlur,
      className,
      size = 28,
      ...props
    },
    ref
  ) => {
    const controls = useAnimation();
    const motionPreference = useRef(false);
    const startAnimation = useCallback(() => {
      if (!motionPreference.current) return controls.start('animate');
    }, [controls]);
    const stopAnimation = useCallback(() => {
      if (motionPreference.current) {
        controls.stop();
        controls.set('normal');
        return;
      }
      return controls.start('normal');
    }, [controls]);
    useEffect(() => {
      const media = window.matchMedia('(prefers-reduced-motion: reduce)');
      const updatePreference = () => {
        motionPreference.current = media.matches;
        if (media.matches) {
          controls.stop();
          controls.set('normal');
        }
      };
      updatePreference();
      media.addEventListener('change', updatePreference);
      return () => {
        media.removeEventListener('change', updatePreference);
        controls.stop();
      };
    }, [controls]);
    const isControlledRef = useRef(false);
    const {
      rootRef: iconRootRef,
      reduceDefinition,
      ...iconAccessibility
    } = useIconAccessibility(ref, () => {
      isControlledRef.current = ref != null;
      return {
        startAnimation: () => startAnimation(),
        stopAnimation: () => stopAnimation(),
      };
    }, [controls]);
    const handleMouseEnter = useCallback(
      (e: React.MouseEvent<HTMLDivElement>) => {
        if (!isControlledRef.current) startAnimation();
        void e;
      },
      [startAnimation]
    );
    const handleMouseLeave = useCallback(
      (e: React.MouseEvent<HTMLDivElement>) => {
        if (!isControlledRef.current) stopAnimation();
        void e;
      },
      [stopAnimation]
    );
    return (
      <div
        className={cn(className)}
        {...props}
        ref={iconRootRef}
        onMouseEnter={(event) => {
          if (!iconAccessibility.controlled && !iconAccessibility.reduced) {
            handleMouseEnter(event);
          }
          onMouseEnter?.(event);
        }}
        onMouseLeave={(event) => {
          if (!iconAccessibility.controlled) {
            handleMouseLeave(event);
          }
          onMouseLeave?.(event);
        }}
        onFocus={(event) => {
          if (!iconAccessibility.controlled && !iconAccessibility.reduced) {
            ((event) => {
              if (!isControlledRef.current) startAnimation();
              void event;
            })(event);
          }
          onFocus?.(event);
        }}
        onBlur={(event) => {
          if (!iconAccessibility.controlled) {
            ((event) => {
              if (!isControlledRef.current) stopAnimation();
              void event;
            })(event);
          }
          onBlur?.(event);
        }}
      >
        <motion.svg
          xmlns="http://www.w3.org/2000/svg"
          width={size}
          height={size}
          viewBox="0 0 24 24"
          fill="none"
          aria-hidden="true"
          focusable="false"
          animate={reduceDefinition(controls)}
          initial="normal"
          variants={{
            normal: { y: 0, scale: 1 },
            animate: {
              y: [0, -4, 0],
              scale: [1, 1.1, 1],
              transition: {
                duration: 0.4,
                ease: 'easeInOut',
                repeat: 1,
                repeatType: 'reverse',
              },
            },
          }}
        >
          <path
            d="M21 5.5V9C21 10.1046 20.1046 11 19 11C17.8954 11 17 10.1046 17 9V5.5C17 4.39543 17.8954 3.5 19 3.5C20.1046 3.5 21 4.39543 21 5.5Z"
            stroke="currentColor"
            strokeLinecap="round"
            strokeWidth="1.5"
          />

          <path
            d="M17 4V9.5C17 10.6046 16.1046 11.5 15 11.5C13.8954 11.5 13 10.6046 13 9.5V4C13 2.89543 13.8954 2 15 2C16.1046 2 17 2.89543 17 4Z"
            stroke="currentColor"
            strokeLinecap="round"
            strokeWidth="1.5"
          />

          <path
            d="M9 7.5V4C9 2.89543 9.89543 2 11 2C12.1046 2 13 2.89543 13 4V9.5"
            stroke="currentColor"
            strokeLinecap="round"
            strokeWidth="1.5"
          />

          <path
            d="M5 8V4.5C5 3.39543 5.89543 2.5 7 2.5C8.10457 2.5 9 3.39543 9 4.5V7"
            stroke="currentColor"
            strokeLinecap="round"
            strokeWidth="1.5"
          />

          <path
            d="M12 17V16C12 13.7909 10.2091 12 8 12H11C12.1046 12 13 11.1046 13 10C13 8.89543 12.1046 8 11 8H7.2C6.08323 8 5.52485 8 5.07295 8.14683C4.15964 8.44358 3.44358 9.15964 3.14683 10.0729C3 10.5248 3 11.0832 3 12.2V13C3 14.8591 3 15.7887 3.1755 16.5576C3.77384 19.1791 5.82088 21.2262 8.44235 21.8245C9.21129 22 10.1409 22 12 22C13.8591 22 14.7887 22 15.5576 21.8245C18.1791 21.2262 20.2262 19.1791 20.8245 16.5576C21 15.7887 21 14.8591 21 13V9"
            stroke="currentColor"
            strokeLinecap="round"
            strokeLinejoin="round"
            strokeWidth="1.5"
          />
        </motion.svg>
      </div>
    );
  }
);
